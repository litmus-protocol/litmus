// Compiles the frozen interfaces with solc 0.8.24 and writes packages/shared/src/abi.generated.ts.
// Usage: pnpm --filter @defect/contracts abi        (regenerate)
//        pnpm --filter @defect/contracts abi:check  (fail if the committed file is out of date)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import solc from "solc";

const here = (rel) => fileURLToPath(new URL(rel, import.meta.url));
const SOURCES = {
  IDefectArena: "../src/interfaces/IDefectArena.sol",
  IDefectAttestations: "../src/interfaces/IDefectAttestations.sol",
  IDefectCertificate: "../src/interfaces/IDefectCertificate.sol",
  IErc8004: "../src/interfaces/IErc8004.sol",
};
const OUT = here("../../shared/src/abi.generated.ts");

const input = {
  language: "Solidity",
  sources: Object.fromEntries(Object.entries(SOURCES).map(([name, rel]) => [`${name}.sol`, { content: readFileSync(here(rel), "utf8") }])),
  settings: { outputSelection: { "*": { "*": ["abi"] } } },
};
const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((e) => e.severity === "error");
if (errors.length) {
  for (const e of errors) console.error(e.formattedMessage);
  process.exit(1);
}

const abiOf = (name, file = name) => output.contracts[`${file}.sol`][name].abi;
const text = `// GENERATED by packages/contracts/scripts/gen-abi.mjs from the frozen Solidity interfaces. Do not edit.
// Source: packages/contracts/src/interfaces/IDefectArena.sol, IDefectAttestations.sol, IDefectCertificate.sol, IErc8004.sol (solc ${solc.version()})

export const defectArenaAbi = ${JSON.stringify(abiOf("IDefectArena"), null, 2)} as const;

export const attestationsAbi = ${JSON.stringify(abiOf("IDefectAttestations"), null, 2)} as const;

export const certificateAbi = ${JSON.stringify(abiOf("IDefectCertificate"), null, 2)} as const;

export const identityRegistryAbi = ${JSON.stringify(abiOf("IErc8004Identity", "IErc8004"), null, 2)} as const;

export const reputationRegistryAbi = ${JSON.stringify(abiOf("IErc8004Reputation", "IErc8004"), null, 2)} as const;
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(OUT, "utf8");
  if (current !== text) {
    console.error("abi.generated.ts is out of date. Run: pnpm --filter @defect/contracts abi");
    process.exit(1);
  }
  console.log("abi.generated.ts is up to date.");
} else {
  writeFileSync(OUT, text);
  const arena = abiOf("IDefectArena");
  const count = (t) => arena.filter((x) => x.type === t).length;
  console.log(`wrote ${OUT}: DefectArena ${count("function")} functions, ${count("event")} events, ${count("error")} errors`);
}
